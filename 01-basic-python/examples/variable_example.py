# Module 01 example: read and explain line by line
# This example demonstrates a beginner-friendly Python pattern using variables and print

name = "Alice"
print(name)

# Explanation:
# 1. `name = "Alice"` stores the text "Alice" in a variable called `name`
# 2. `print(name)` displays the value currently stored in `name`
# 3. This is useful because you can reuse variables instead of manually typing values repeatedly

# Why it matters:
# Variables help us write clean, maintainable code.

